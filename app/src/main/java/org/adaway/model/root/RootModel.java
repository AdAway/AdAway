/**
 * This class is the model to represent hosts file installation.
 *
 * @author Bruce BUJON (bruce.bujon(at)gmail(dot)com)
 */
public class RootModel extends AdBlockModel {
    private static final String HEADER1 = "# This hosts file has been generated by AdAway on: ";
    private static final String HEADER2 = "# Please do not modify it directly, it will be overwritten when AdAway is applied again.";
    private static final String HEADER_SOURCES = "# This file is generated from the following sources:";
    private static final int HOSTS_FILE_BUFFER_SIZE = 1024 * 1024;
    private static final int HOSTS_FILE_CHUNK_ROWS = 8192;
    private static final byte[] LINE_SEPARATOR_BYTES =
            LINE_SEPARATOR.getBytes(StandardCharsets.UTF_8);
    private final HostsSourceDao hostsSourceDao;
    private final HostEntryDao hostEntryDao;

    /**
     * Constructor.
     *
     * @param context The application context.
     */
    public RootModel(Context context) {
        super(context);
        // Get DOA
        AppDatabase database = AppDatabase.getInstance(this.context);
        this.hostsSourceDao = database.hostsSourceDao();
        this.hostEntryDao = database.hostEntryDao();
        // Check if host list is applied
        Executor executor = AppExecutors.getInstance().diskIO();
        executor.execute(this::checkApplied);
        executor.execute(() -> syncPreferences(context));
    }

    @Override
    public AdBlockMethod getMethod() {
        return ROOT;
    }

    @Override
    public void apply() throws HostErrorException {
        setState(R.string.status_apply_sources);
        setState(R.string.status_create_new_hosts);
        createNewHostsFile();
        setState(R.string.status_copy_new_hosts);
        copyNewHostsFile();
        setState(R.string.status_check_copy);
        setState(R.string.status_hosts_updated);
        this.applied.postValue(true);
    }

    /**
     * Revert to the default hosts file.
     *
     * @throws HostErrorException If the hosts file could not be reverted.
     */
    @Override
    public void revert() throws HostErrorException {
        // Update status
        setState(R.string.status_revert);
        try {
            // Revert hosts file
            revertHostFile();
            setState(R.string.status_revert_done);
            this.applied.postValue(false);
        } catch (IOException exception) {
            throw new HostErrorException(REVERT_FAIL, exception);
        }
    }

    @Override
    public boolean isRecordingLogs() {
        return TcpdumpUtils.isTcpdumpRunning();
    }

    @Override
    public void setRecordingLogs(boolean recording) {
        if (recording) {
            TcpdumpUtils.startTcpdump(this.context);
        } else {
            TcpdumpUtils.stopTcpdump();
        }
    }

    @Override
    public List<String> getLogs() {
        return TcpdumpUtils.getLogs(this.context);
    }

    @Override
    public void clearLogs() {
        TcpdumpUtils.clearLogFile(this.context);
    }

    private void checkApplied() {
        boolean applied = false;

        Shell.Result result = Shell.cmd("head -n 1 " + com.topjohnwu.superuser.ShellUtils.escapedString(ANDROID_SYSTEM_ETC_HOSTS)).exec();
        if (!result.isSuccess()) {
            Timber.e("Failed to read first line of hosts file. Error code: %s", result.getCode());
        } else {
            applied = mergeAllLines(result.getOut()).startsWith(HEADER1);
        }

        this.applied.postValue(applied);
    }

    private void syncPreferences(Context context) {
        WebServerUtils.stopWebServer();
    }

    private void deleteNewHostsFile() {
        // delete generated hosts file from private storage
        this.context.deleteFile(HOSTS_FILENAME);
    }

    private void copyNewHostsFile() throws HostErrorException {
        try {
            copyHostsFile(HOSTS_FILENAME);
        } catch (CommandException exception) {
            throw new HostErrorException(COPY_FAIL, exception);
        }
    }

    /**
     * Create a new hosts files in a private file from downloaded hosts sources.
     *
     * @throws HostErrorException If the new hosts file could not be created.
     */
    private void createNewHostsFile() throws HostErrorException {
        deleteNewHostsFile();
        try (HostsFileWriter writer = new HostsFileWriter(
                this.context.openFileOutput(HOSTS_FILENAME, MODE_PRIVATE))) {
            writeHostsHeader(writer);
            writeLoopbackToHosts(writer);
            writeHosts(writer);
        } catch (IOException exception) {
            throw new HostErrorException(PRIVATE_FILE_FAILED, exception);
        }
    }

    private void writeHostsHeader(HostsFileWriter writer) throws IOException {
        // Format current date
        SimpleDateFormat formatter = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US);
        Date now = new Date();
        String date = formatter.format(now);
        // Write header
        writer.write(HEADER1);
        writer.write(date);
        writer.newLine();
        writer.write(HEADER2);
        writer.newLine();
        // Write hosts source
        writer.write(HEADER_SOURCES);
        writer.newLine();
        for (HostsSource hostsSource : this.hostsSourceDao.getEnabled()) {
            writer.write(sourceHeader(hostsSource.getLabel(), hostsSource.getUrl()));
            writer.newLine();
        }
        // Write empty line separator
        writer.newLine();
    }

    static String sourceHeader(String label, String url) {
        // Source metadata is a comment, never an additional hosts-file entry.
        return ("# - " + label + ":" + url).replace('\r', ' ').replace('\n', ' ');
    }

    private void writeLoopbackToHosts(HostsFileWriter writer) throws IOException {
        writer.write(LOCALHOST_IPV4 + " " + LOCALHOST_HOSTNAME);
        writer.newLine();
        writer.write(LOCALHOST_IPV6 + " " + LOCALHOST_HOSTNAME);
        writer.newLine();
    }

    private void writeHosts(HostsFileWriter writer) throws IOException {
        // Get user preferences
        String redirectionIpv4 = PreferenceHelper.getRedirectionIpv4(this.context);
        String redirectionIpv6 = PreferenceHelper.getRedirectionIpv6(this.context);
        boolean enableIpv6 = PreferenceHelper.getEnableIpv6(this.context);
        if (this.hostEntryDao.hasMaterializedRootExportRows()) {
            writeMaterializedHosts(writer, redirectionIpv4, redirectionIpv6, enableIpv6);
            return;
        }

        writeActiveHosts(writer, redirectionIpv4, redirectionIpv6, enableIpv6);
    }

    private void writeMaterializedHosts(HostsFileWriter writer, String redirectionIpv4,
            String redirectionIpv6, boolean enableIpv6) throws IOException {
        if (this.hostEntryDao.getActiveRuntimeRuleCountNow() > 0) {
            writeMaterializedHostChunks(writer, redirectionIpv4, redirectionIpv6, enableIpv6);
            return;
        }
        try (Cursor cursor = this.hostEntryDao.getRootHostsFileCursorMaterialized()) {
            writeHostsFromCursor(writer, cursor, redirectionIpv4, redirectionIpv6, enableIpv6);
        }
    }

    private void writeMaterializedHostChunks(HostsFileWriter writer, String redirectionIpv4,
            String redirectionIpv6, boolean enableIpv6) throws IOException {
        long afterId = 0;
        boolean stageBacked = this.hostEntryDao.hasStageMaterializedRootExportRows();
        int activeGeneration = stageBacked ? this.hostEntryDao.getActiveGeneration() : 0;
        while (true) {
            try (Cursor cursor = openMaterializedHostChunkCursor(
                    redirectionIpv4, redirectionIpv6, enableIpv6, afterId, stageBacked,
                    activeGeneration)) {
                if (!cursor.moveToFirst()) {
                    return;
                }
                int rowCountColumn = cursor.getColumnIndexOrThrow("row_count");
                int rowCount = cursor.getInt(rowCountColumn);
                if (rowCount == 0) {
                    return;
                }
                int linesColumn = cursor.getColumnIndexOrThrow("lines");
                writer.writeChunk(cursor.getString(linesColumn));
                writer.newLine();
                int lastIdColumn = cursor.getColumnIndexOrThrow("last_id");
                afterId = cursor.getLong(lastIdColumn);
                if (rowCount < HOSTS_FILE_CHUNK_ROWS) {
                    return;
                }
            }
        }
    }

    private Cursor openMaterializedHostChunkCursor(String redirectionIpv4, String redirectionIpv6,
            boolean enableIpv6, long afterId, boolean stageBacked, int activeGeneration) {
        if (stageBacked) {
            return enableIpv6
                    ? this.hostEntryDao.getRootHostsFileChunkCursorStageMaterializedIpv6(
                            redirectionIpv4, redirectionIpv6, LINE_SEPARATOR, afterId,
                            HOSTS_FILE_CHUNK_ROWS, activeGeneration)
                    : this.hostEntryDao.getRootHostsFileChunkCursorStageMaterialized(
                            redirectionIpv4, LINE_SEPARATOR, afterId, HOSTS_FILE_CHUNK_ROWS,
                            activeGeneration);
        }
        return enableIpv6
                ? this.hostEntryDao.getRootHostsFileChunkCursorMaterializedIpv6(
                        redirectionIpv4, redirectionIpv6, LINE_SEPARATOR, afterId,
                        HOSTS_FILE_CHUNK_ROWS)
                : this.hostEntryDao.getRootHostsFileChunkCursorMaterialized(
                        redirectionIpv4, LINE_SEPARATOR, afterId, HOSTS_FILE_CHUNK_ROWS);
    }

    private void writeActiveHosts(HostsFileWriter writer, String redirectionIpv4,
            String redirectionIpv6, boolean enableIpv6) throws IOException {
        try (Cursor cursor = this.hostEntryDao.getActiveRootHostsFileCursor()) {
            writeHostsFromCursor(writer, cursor, redirectionIpv4, redirectionIpv6, enableIpv6);
        }
    }

    private static void writeHostsFromCursor(HostsFileWriter writer, Cursor cursor,
            String redirectionIpv4, String redirectionIpv6, boolean enableIpv6)
            throws IOException {
        byte[] redirectionIpv4Prefix = createRedirectionPrefix(redirectionIpv4);
        byte[] redirectionIpv6Prefix = createRedirectionPrefix(redirectionIpv6);
        int hostColumn = cursor.getColumnIndexOrThrow("host");
        int typeColumn = cursor.getColumnIndexOrThrow("type");
        int redirectionColumn = cursor.getColumnIndexOrThrow("redirection");
        while (cursor.moveToNext()) {
            String hostname = cursor.getString(hostColumn);
            if (cursor.getInt(typeColumn) == REDIRECTED.getValue()) {
                writeHostLine(writer, cursor.getString(redirectionColumn), hostname);
                continue;
            }
            writeHostLine(writer, redirectionIpv4Prefix, hostname);
            if (enableIpv6) {
                writeHostLine(writer, redirectionIpv6Prefix, hostname);
            }
        }
    }

    private static byte[] createRedirectionPrefix(String redirection) {
        return (redirection + " ").getBytes(StandardCharsets.UTF_8);
    }

    private static void writeHostLine(HostsFileWriter writer, byte[] redirectionPrefix,
            String hostname) throws IOException {
        writer.write(redirectionPrefix);
        writer.write(hostname);
        writer.newLine();
    }

    private static void writeHostLine(HostsFileWriter writer, String redirection, String hostname)
            throws IOException {
        writer.write(redirection);
        writer.write(' ');
        writer.write(hostname);
        writer.newLine();
    }

    private static final class HostsFileWriter implements Closeable {
        private final OutputStream output;
        private final byte[] buffer;
        private int position;

        HostsFileWriter(OutputStream output) {
            this.output = new BufferedOutputStream(output, HOSTS_FILE_BUFFER_SIZE);
            this.buffer = new byte[HOSTS_FILE_BUFFER_SIZE];
        }

        void write(String value) throws IOException {
            if (value == null) {
                return;
            }
            int length = value.length();
            int index = 0;
            while (index < length) {
                if (this.position == this.buffer.length) {
                    flushBuffer();
                }
                int count = Math.min(this.buffer.length - this.position, length - index);
                int copied = 0;
                while (copied < count) {
                    char character = value.charAt(index + copied);
                    if (character > 0x7F) {
                        this.position += copied;
                        writeUtf8(value.substring(index + copied));
                        return;
                    }
                    this.buffer[this.position + copied] = (byte) character;
                    copied++;
                }
                this.position += copied;
                index += copied;
            }
        }

        void write(char value) throws IOException {
            write((byte) value);
        }

        void writeChunk(String value) throws IOException {
            if (value == null) {
                return;
            }
            writeUtf8(value);
        }

        void newLine() throws IOException {
            write(LINE_SEPARATOR_BYTES);
        }

        private void writeUtf8(String value) throws IOException {
            flushBuffer();
            this.output.write(value.getBytes(StandardCharsets.UTF_8));
        }

        private void write(byte[] value) throws IOException {
            int index = 0;
            while (index < value.length) {
                if (this.position == this.buffer.length) {
                    flushBuffer();
                }
                int count = Math.min(this.buffer.length - this.position, value.length - index);
                System.arraycopy(value, index, this.buffer, this.position, count);
                this.position += count;
                index += count;
            }
        }

        private void write(byte value) throws IOException {
            if (this.position == this.buffer.length) {
                flushBuffer();
            }
            this.buffer[this.position++] = value;
        }

        private void flushBuffer() throws IOException {
            if (this.position > 0) {
                this.output.write(this.buffer, 0, this.position);
                this.position = 0;
            }
        }

        @Override
        public void close() throws IOException {
            flushBuffer();
            this.output.close();
        }
    }

    /**
     * Revert to default hosts file.
     *
     * @throws IOException If the hosts file could not be reverted.
     */
    private void revertHostFile() throws IOException {
        // Create private file
        try (FileOutputStream fos = this.context.openFileOutput(DEFAULT_HOSTS_FILENAME, MODE_PRIVATE)) {
            // Write default localhost as hosts file
            String localhost = LOCALHOST_IPV4 + " " + LOCALHOST_HOSTNAME + LINE_SEPARATOR +
                    LOCALHOST_IPV6 + " " + LOCALHOST_HOSTNAME + LINE_SEPARATOR;
            fos.write(localhost.getBytes());
            // Copy generated hosts file to target location
            copyHostsFile(DEFAULT_HOSTS_FILENAME);
            // Delete generated hosts file after applying it
            this.context.deleteFile(DEFAULT_HOSTS_FILENAME);
        } catch (Exception exception) {
            throw new IOException("Unable to revert hosts file.", exception);
        }
    }

    /**
     * Copy source file from private storage of AdAway to hosts file target using root commands.
     */
    private void copyHostsFile(String source) throws HostErrorException, CommandException {
        String privateDir = this.context.getFilesDir().getAbsolutePath();
        String privateFile = privateDir + File.separator + source;

        // if the target has a trailing slash, it is not a valid target!
        String target = ANDROID_SYSTEM_ETC_HOSTS;
        File targetFile = new File(target);

        /* check for space on partition */
        long size = new File(privateFile).length();
        Timber.i("Size of hosts file: %s.", size);
        if (!hasEnoughSpaceOnPartition(targetFile, size)) {
            throw new HostErrorException(NOT_ENOUGH_SPACE);
        }

        /* Execute commands */
        boolean writable = isWritable(targetFile);
        try {
            if (!writable) {
                // remount for write access
                Timber.i("Remounting for RW…");
                if (!ShellUtils.remountPartition(targetFile, READ_WRITE)) {
                    throw new CommandException("Failed to remount hosts file partition as read-write.");
                }
            }
            // Copy hosts file then set owner and permissions
            Shell.Result result = Shell.cmd(
                    ShellUtils.hostsCopyCommand(privateFile, target)).exec();
            if (!result.isSuccess()) {
                throw new CommandException("Failed to copy hosts file: " + mergeAllLines(result.getErr()));
            }
        } finally {
            if (!writable) {
                // after all remount target back as read only
                ShellUtils.remountPartition(targetFile, READ_ONLY);
            }
        }
    }

    /**
     * Check if there is enough space on partition where target is located
     *
     * @param size   size of file to put on partition
     * @param target path where to put the file
     * @return true if it will fit on partition of target, false if it will not fit.
     */
    private boolean hasEnoughSpaceOnPartition(File target, long size) {
        long freeSpace = target.getFreeSpace();
        return (freeSpace == 0 || freeSpace > size);
    }
}
